# Pre-load CSVs once; skip priors without usable data
loaded = {}
for spec in PRIOR_SPECS:
    if not os.path.exists(spec['csv']):
        print(f"  [{spec['name']}] CSV not found — skipping")
        continue
    df = pd.read_csv(spec['csv'])
    df['event_id'] = df['event_id'].astype(str)
    if column_err not in df.columns or df[column_err].isna().all():
        print(f"  [{spec['name']}] no map_err_km data — skipping")
        continue
    df = df.dropna(subset=[column_err]).copy()
    if 'n_trigs' not in df.columns:
        df['n_trigs'] = (df.groupby('event_id')['version']
                           .rank(method='dense')
                           .astype(int))
    loaded[spec['name']] = (spec, df)

def _plot_error_count_panel(loaded_dfs, fig_num, region_label, save_name):
    """2x2 panel: count of events with location error >= threshold vs trigger count."""
    fig, axes = plt.subplots(2, 2, figsize=(13, 9), sharex=True)
    axes = axes.flatten()

    for ax, threshold in zip(axes, COVERAGE_RADII_KM):
        for name, (spec, df) in loaded_dfs.items():
            counts = (df.groupby('n_trigs')[column_err]
                        .apply(lambda x: (x >= threshold).sum())
                        .reset_index(name='n_large_errors'))
            n_events = df['event_id'].nunique()
            ax.plot(counts['n_trigs'], counts['n_large_errors'],
                    color=color_lookup.get(name, 'gray'),
                    linestyle=spec['ls'], linewidth=spec['lw'],
                    label=f"{name}  (n={n_events})")

        ax.set_title(f'Error ≥ {threshold} km', fontsize=11)
        ax.set_xlim(left=_XLIM_LEFT)
        ax.set_yscale('log')
        ax.grid(True, alpha=0.3)

    for ax in axes[2:]:
        ax.set_xlabel('Number of triggers', fontsize=11)
    for ax in axes[::2]:
        ax.set_ylabel('Event count  (↓ better)', fontsize=11)

    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, fontsize=8, loc='lower center',
               ncol=min(len(loaded_dfs), 4), bbox_to_anchor=(0.5, -0.02))
    fig.suptitle(f'Figure {fig_num}: {region_label}Events exceeding error threshold vs trigger count — {PLOT_TITLE_SUFFIX}',
                 fontsize=13)
    plt.tight_layout(rect=[0, 0.06, 1, 1])

    save_path = os.path.join(FIGURES_DIR, save_name)
    fig.savefig(save_path, dpi=150, bbox_inches='tight')
    print(f'Saved: {save_path}')
    plt.show()
    return fig

