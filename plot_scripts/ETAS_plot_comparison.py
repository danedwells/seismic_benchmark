def _plot_error_histogram_grid(get_vals, fig_num, region_label, n_trigs, save_name):
    """2x3 panel: histogram of location error per prior, with a reference overlay."""
    bins = np.logspace(-1, 3, 20)
    positions = [(0.02, 0.5), (0.36, 0.5), (0.7, 0.5),
                 (0.02, 0.02), (0.36, 0.02), (0.7, 0.02)]
    fig = plt.figure(figsize=(14, 8), dpi=300)
    axes = [fig.add_axes([x, y, 0.28, 0.43]) for x, y in positions]

    ref_stats = get_vals(REFERENCE_PRIOR, n_trigs)

    # zip (not enumerate + PRIOR_SPECS[i]) so this doesn't IndexError when fewer
    # than 6 PRIOR_SPECS are active (e.g. most of COMPARISON_RUNS commented out) —
    # unused axes are hidden below rather than assumed to exist 1:1 with axes.
    for ax, spec in zip(axes, PRIOR_SPECS):
        stats = get_vals(spec['name'], n_trigs)
        if ref_stats is not None:
            ax.hist(ref_stats, bins=bins, rwidth=0.9, color='b',
                    label=[f'{REFERENCE_PRIOR}  (ref)'], alpha=0.4)
        # stats is None when spec['csv'] hasn't been run yet (e.g. an ETAS
        # config from COMPARISON_RUNS not yet benchmarked); skip rather than crash.
        if stats is not None:
            ax.hist(stats, bins=bins, rwidth=0.9, color='r', alpha=0.6)
        ax.set_xscale('log')
        ax.set_title(spec['name'])
        ax.grid()

        # Annotate median error and modal bin (by count) in the top-right corner
        if stats is not None and len(stats) > 0:
            median_err = np.median(stats)
            counts, edges = np.histogram(stats, bins=bins)
            mode_idx = np.argmax(counts)
            mode_lo, mode_hi = edges[mode_idx], edges[mode_idx + 1]
            stats_text = f"median: {median_err:.1f} km\nmode: {mode_lo:.1f}–{mode_hi:.1f} km"
            ax.text(0.95, 0.95, stats_text, transform=ax.transAxes,
                    ha='right', va='top', fontsize=9,
                    bbox=dict(boxstyle='round', facecolor='white', alpha=0.7, edgecolor='none'))

        if ax is axes[0]:
            ax.legend(loc='upper left')

    # Hide any axes beyond len(PRIOR_SPECS) — the 2x3 layout is fixed regardless
    # of how many COMPARISON_RUNS entries are active.
    for ax in axes[len(PRIOR_SPECS):]:
        ax.set_visible(False)

    y_max = max(ax.get_ylim()[1] for ax in axes[:len(PRIOR_SPECS)])
    for ax in axes[:len(PRIOR_SPECS)]:
        ax.set_ylim(0, y_max)

    for ax in axes[:3]:
        ax.set_xticklabels([])
    for ax in [axes[1], axes[2], axes[4], axes[5]]:
        ax.set_yticklabels([])
    for ax in axes[3:]:
        ax.xaxis.set_major_formatter(FuncFormatter(lambda x, _: f'{x:g}'))
        ax.set_xlabel('Location error (km)', fontsize=11)
    for ax in [axes[0], axes[3]]:
        ax.set_ylabel('Event count', fontsize=11)

    fig.suptitle(f"Figure {fig_num}: {region_label}{PLOT_TITLE_SUFFIX}  Number of triggers: {n_trigs}",
                fontsize=16)

    plt.show()
    save_path = os.path.join(FIGURES_DIR, save_name)
    fig.savefig(save_path, bbox_inches='tight')
    print(f'Saved: {save_path}')
    return fig

