# ---------------------------------------------------------------------------
# Figure 1: usgs_credible_level vs trigger count
# ---------------------------------------------------------------------------
# The smallest HDR fraction needed to contain the USGS location.
# Lower = better (USGS falls in a high-probability region of the posterior).
# A perfectly calibrated posterior gives Uniform(0,1) across events →
# median converges to 0.5.  Values well below 0.5 mean the posterior is
# confidently pointing toward the true location.
# ---------------------------------------------------------------------------
fig_cred = plot_metric_vs_triggers(
    metric     = 'usgs_credible_level',
    ylabel     = 'Median usgs_credible_level  (↓ better)',
    title      = f'Posterior calibration vs trigger count — {PLOT_TITLE_SUFFIX}',
    ylim       = (0, 1),
    ref_line   = 0.5,
    ref_label  = 'calibrated median  (0.5)',
    save_path  = os.path.join(FIGURES_DIR, 'credible_level_vs_triggers.png'),
)
plt.show()

