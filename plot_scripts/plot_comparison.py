def load_per_version_stats(csv_path, metric, min_events=5):
    """
    Load a benchmark CSV and return per-trigger-count aggregate statistics.

    Parameters
    ----------
    csv_path : str
    metric : str
        Column to aggregate (e.g. 'usgs_credible_level', 'map_err_km').
    min_events : int
        Drop trigger counts represented by fewer than this many events.

    Returns
    -------
    DataFrame with columns [n_trigs, median, q10, q90, count], or None if
    the file is missing or the metric column is entirely NaN.

    Notes
    -----
    version is 0-indexed in the CSV (version 0 = first trigger to arrive),
    so n_trigs = version + 1.  If existing CSVs only have metrics on the
    final row (old format), only that single point will appear on the plot.
    """
    if not os.path.exists(csv_path):
        return None
    df = pd.read_csv(csv_path)
    if metric not in df.columns or df[metric].isna().all():
        return None

    df = df.dropna(subset=[metric]).copy()
    if 'n_trigs' not in df.columns:
        # fallback for CSVs generated before n_trigs was added to the runner
        df['n_trigs'] = (df.groupby('event_id')['version']
                           .rank(method='dense')
                           .astype(int))

    stats = (df.groupby('n_trigs')[metric]
               .agg(median='median',
                    q10=lambda x: x.quantile(0.1),
                    q90=lambda x: x.quantile(0.9),
                    q5=lambda x: x.quantile(0.05),
                    q95=lambda x: x.quantile(0.95),
                    min='min',
                    max='max',
                    count='count')
               .reset_index())
    return stats[stats['count'] >= min_events]


def plot_metric_vs_triggers(metric, ylabel, title, save_path=None,
                            ylim=None, ref_line=None, ref_label=None,
                            log_y=False):
    """
    Plot median metric vs trigger count for all priors, with IQR shading.

    Parameters
    ----------
    metric : str
        Column name in the benchmark CSVs.
    ylabel : str
        Y-axis label (include direction hint, e.g. '↓ better').
    title : str
        Figure title.
    save_path : str or None
    ylim : tuple or None
        (ymin, ymax) passed to ax.set_ylim.  None = matplotlib auto.
    ref_line : float or None
        If given, draws a horizontal dashed reference line at this value.
    ref_label : str or None
        Legend label for the reference line.
    """
    colors = plt.cm.tab10.colors
    fig, ax = plt.subplots(figsize=(10, 6))

    for i, spec in enumerate(PRIOR_SPECS):
        stats = load_per_version_stats(spec['csv'], metric)
        if stats is None:
            print(f"  [{spec['name']}] no data for '{metric}' — skipping")
            continue

        color = colors[i % len(colors)]
        n_max = int(stats['count'].max())
        ax.plot(stats['n_trigs'], stats['median'],
                color=color, linestyle='-', linewidth=2.5,
                label=f"{spec['name']}  (n≈{n_max})")
        ax.fill_between(stats['n_trigs'], stats['q5'], stats['q95'],
                        color=color, alpha=0.06)
        ax.plot(stats['n_trigs'], stats['q5'],
                color=color, linestyle='solid', linewidth=0.6, alpha=0.5)
        ax.plot(stats['n_trigs'], stats['q95'],
                color=color, linestyle='solid', linewidth=0.6, alpha=0.5)

    if ref_line is not None:
        ax.axhline(ref_line, color='gray', linestyle=':', linewidth=1,
                   label=ref_label or str(ref_line))

    ax.set_xlabel('Number of triggers', fontsize=12)
    ax.set_ylabel(ylabel, fontsize=12)
    ax.set_title(title, fontsize=13)
    ax.set_xlim(left=1)
    if log_y:
        ax.set_yscale('log')
    if ylim is not None:
        ax.set_ylim(*ylim)
    ax.legend(fontsize=9, loc='upper right')
    plt.tight_layout()

    if save_path is not None:
        plt.savefig(save_path, dpi=150, bbox_inches='tight')
        print(f'Saved: {save_path}')
    return fig


