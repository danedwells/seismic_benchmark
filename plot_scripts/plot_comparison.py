# ---------------------------------------------------------------------------
# Figure 2: posterior coverage at fixed radii vs trigger count (2×2 panel)
# ---------------------------------------------------------------------------
# Fraction of posterior probability mass within a fixed radius of the USGS
# location.  Higher = better.  All four radii in one 2×2 figure.
# ---------------------------------------------------------------------------
